"""Textos de la app en español, inglés y francés.

El idioma activo se guarda a nivel de módulo (set_language) para que cualquier parte del
código pueda llamar a t('clave') sin tener que ir pasando el idioma por parámetro.
Las claves internas de datos (nombres de deporte como 'Ciclismo') NO se traducen: son
identificadores; solo se traduce lo que se muestra en pantalla.
"""

LANGUAGES = {'es': 'Español', 'en': 'English', 'fr': 'Français'}

_state = {'lang': 'es'}


def set_language(lang):
    if lang in LANGUAGES:
        _state['lang'] = lang


def get_language():
    return _state['lang']


def t(key, lang=None):
    """Texto traducido de `key`. Si falta en el idioma activo, cae al español y, si tampoco
    está, devuelve la propia clave (así un texto sin traducir se ve, pero no rompe nada)."""
    language = lang or _state['lang']
    return TRANSLATIONS.get(language, {}).get(key) or TRANSLATIONS['es'].get(key, key)


